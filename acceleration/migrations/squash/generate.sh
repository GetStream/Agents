#!/usr/bin/env bash
# Rewrites the block of cleanup.sql that the migration files decide: each set's migrations after
# its initial one, the tables, sequences and functions the sets leave, and the fingerprint of a
# new database of each kind before and after those migrations. It builds the databases in a
# throwaway postgres:18 container, the major version the deployments run, applying each file's
# Up as goose would: in one transaction unless the file says NO TRANSACTION.
#
#   generate.sh
#
# Run it from anywhere once a migration is added before the release that squashes the history.
set -euo pipefail

here=$(cd "$(dirname "$0")" && pwd)
migrations=$(dirname "$here")
cleanup="$here/cleanup.sql"
initial=20270110000000
container="squash-generate-$$"

docker run -d --rm --name "$container" -e POSTGRES_PASSWORD=postgres postgres:18-alpine >/dev/null
trap 'docker rm -f "$container" >/dev/null 2>&1 || true' EXIT
until docker exec "$container" pg_isready -U postgres -q 2>/dev/null; do sleep 1; done
sleep 1

psql() { docker exec -i -e PGOPTIONS="-c client_min_messages=warning" "$container" psql -U postgres -X -q -v ON_ERROR_STOP=1 "$@"; }

# apply <database> <set> <before|after>: the set's initial migration, and with after the rest.
apply() {
  local file
  for file in "$migrations/$2"/*.sql; do
    if [[ $3 == before && $(basename "$file") != ${initial}_* ]]; then
      continue
    fi
    if grep -q -- '-- +goose NO TRANSACTION' "$file"; then
      sed '/^-- +goose Down/,$d' "$file" | psql -d "$1" -f - >/dev/null
    else
      sed '/^-- +goose Down/,$d' "$file" | psql -d "$1" -1 -f - >/dev/null
    fi
  done
}

for kind in global shard both; do
  for stage in before after; do
    psql -c "CREATE DATABASE ${kind}_${stage}"
    case $kind in
      global | shard) apply "${kind}_${stage}" "$kind" "$stage" ;;
      both) apply "both_${stage}" global "$stage" && apply "both_${stage}" shard "$stage" ;;
    esac
  done
done

list() { psql -d "$1" -At -c "SELECT '{' || coalesce(string_agg(name, ',' ORDER BY name), '') || '}' FROM ($2) AS listed (name)"; }

block=$(mktemp)
for set in global shard; do
  after=$(find "$migrations/$set" -name '*.sql' | sed 's|.*/||; s|_.*||' | sort | awk -v initial=$initial '$1 > initial' | paste -sd, -)
  echo "\\set ${set}_after '{${after}}'" >> "$block"
done
for set in global shard; do
  echo "\\set ${set}_tables '$(list "${set}_after" "SELECT relname FROM pg_class WHERE relnamespace = 'public'::regnamespace AND relkind IN ('r', 'p')")'" >> "$block"
  echo "\\set ${set}_sequences '$(list "${set}_after" "SELECT relname FROM pg_class WHERE relnamespace = 'public'::regnamespace AND relkind = 'S'")'" >> "$block"
  echo "\\set ${set}_functions '$(list "${set}_after" "SELECT DISTINCT proname FROM pg_proc WHERE pronamespace = 'public'::regnamespace")'" >> "$block"
done
for kind in global shard both; do
  for stage in before after; do
    echo "\\set ${kind}_${stage}_fingerprint 'unset'" >> "$block"
  done
done

# write: cleanup.sql with the block between its markers replaced by the file given.
write() {
  awk -v block="$1" '
    /^-- BEGIN generated by generate.sh$/ { print; while ((getline line < block) > 0) print line; skip = 1; next }
    /^-- END generated by generate.sh$/ { skip = 0 }
    !skip { print }
  ' "$cleanup" > "$cleanup.new"
  mv "$cleanup.new" "$cleanup"
}
write "$block"

# The fingerprints are taken by cleanup.sql itself, of the lists just written.
for kind in global shard both; do
  for stage in before after; do
    fingerprint=$(psql -d "${kind}_${stage}" -At -v set="$kind" -v fingerprint_only=1 -f - < "$cleanup")
    sed -i.bak "s|^\\\\set ${kind}_${stage}_fingerprint .*|\\\\set ${kind}_${stage}_fingerprint '${fingerprint}'|" "$block"
  done
done
rm -f "$block.bak"
write "$block"
rm -f "$block"
sed -n '/^-- BEGIN generated by generate.sh$/,/^-- END generated by generate.sh$/p' "$cleanup" | cut -c1-120
