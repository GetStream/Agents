package store

import (
	"context"
	"fmt"
	"slices"
	"strings"

	"github.com/uptrace/bun"

	"github.com/GetStream/Vision-Agents/acceleration/internal/stack"
)

// schemaHeader opens every schema description, so a reader knows not to edit it.
const schemaHeader = "-- Generated by `go run ./cmd/schema` from the migrations. Do not edit.\n"

// Schema describes the tables each migration set leaves, read from the catalogue: columns,
// constraints, indexes and triggers. It is what acceleration/schema holds, so a change to the
// schema shows in review as a change to those files.
func (s *Store) Schema(ctx context.Context) (global, shard string, err error) {
	if global, err = describeSet(ctx, s.global, globalSet); err != nil {
		return "", "", err
	}
	if shard, err = describeSet(ctx, s.shard, shardSet); err != nil {
		return "", "", err
	}
	return global, shard, nil
}

func describeSet(ctx context.Context, db *bun.DB, set migrationSet) (string, error) {
	tables, err := setTables(set)
	if err != nil {
		return "", stack.Wrap(err)
	}
	tables = append(tables, changeLogTables...)
	slices.Sort(tables)

	var out strings.Builder
	out.WriteString(schemaHeader)
	for _, table := range tables {
		described, err := describeTable(ctx, db, table)
		if err != nil {
			return "", err
		}
		out.WriteString("\n" + described)
	}
	return out.String(), nil
}

func describeTable(ctx context.Context, db *bun.DB, table string) (string, error) {
	var lines []string
	err := db.NewRaw(`
SELECT format('    %s %s%s%s', a.attname, format_type(a.atttypid, a.atttypmod),
              CASE WHEN a.attnotnull THEN ' NOT NULL' ELSE '' END,
              COALESCE(' DEFAULT ' || pg_get_expr(d.adbin, d.adrelid), ''))
FROM pg_attribute a
LEFT JOIN pg_attrdef d ON d.adrelid = a.attrelid AND d.adnum = a.attnum
WHERE a.attrelid = ?::regclass AND a.attnum > 0 AND NOT a.attisdropped
ORDER BY a.attname`, table).Scan(ctx, &lines)
	if err != nil {
		return "", stack.Wrap(fmt.Errorf("store: describe %s: %w", table, err))
	}
	var rest []string
	err = db.NewRaw(`
SELECT line FROM (
  SELECT 1 AS kind, conname AS name, format('    CONSTRAINT %s %s', conname, pg_get_constraintdef(oid)) AS line
  FROM pg_constraint WHERE conrelid = ?0::regclass AND contype IN ('p', 'u', 'f', 'c', 'x')
  UNION ALL
  SELECT 2, i.relname, format('    %s', pg_get_indexdef(i.oid))
  FROM pg_index x JOIN pg_class i ON i.oid = x.indexrelid
  WHERE x.indrelid = ?0::regclass
    AND NOT EXISTS (SELECT 1 FROM pg_constraint c WHERE c.conindid = i.oid AND c.contype IN ('p', 'u', 'x'))
  UNION ALL
  SELECT 3, tgname, format('    %s', pg_get_triggerdef(oid))
  FROM pg_trigger WHERE tgrelid = ?0::regclass AND NOT tgisinternal AND tgname <> 'data_changes_recorded'
) described ORDER BY kind, name`, table).Scan(ctx, &rest)
	if err != nil {
		return "", stack.Wrap(fmt.Errorf("store: describe %s: %w", table, err))
	}
	return "TABLE " + table + "\n" + strings.Join(append(lines, rest...), "\n") + "\n", nil
}
